// xy + xz + yz = 36. These are all nine positive, ordered integer solutions.
const integerCuboids: [number, number, number][] = [
  [2, 2, 8],
  [2, 3, 6],
  [2, 6, 3],
  [2, 8, 2],
  [3, 2, 6],
  [3, 6, 2],
  [6, 2, 3],
  [6, 3, 2],
  [8, 2, 2],
];

