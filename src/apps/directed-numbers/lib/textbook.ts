function expand(exercise: "2B" | "2C", rows: Row[]): TextbookQuestion[] {
  return rows.flatMap(([question, expressions, answers]) =>
    expressions.map((expression, index) => ({
      id: `${exercise}-${question}${"abcd"[index]}`,
      exercise,
      question,
      part: "abcd"[index],
      expression,
      answer: answers[index],
      level: (exercise === "2B" ? question >= 21 : question >= 20) ? 2 : 1,
      page:
        exercise === "2B"
          ? question <= 10
            ? 32
            : question <= 26
              ? 33
              : 34
          : question <= 4
            ? 46
            : question <= 16
              ? 47
              : 48,
    })),
  );
}
