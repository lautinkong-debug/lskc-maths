import type { Point, Shape } from "../similarity/types";
import type { TextbookStep } from "../similarity/textbook-types";
import type { CongruenceQuestion } from "./types";

const m = String.raw;
const point = (label: string, x: number, y: number): Point => ({ label, x, y });
const triangles = (...names: string[]): Shape[] =>
  names.map((name) => ({ name: `△${name}`, vertices: [...name] }));
const heading = (text: string): TextbookStep => ({
  heading: text,
  highlights: {
    figures: [...text.matchAll(/△([A-Z]{3})/g)].map((match) => match[1]),
  },
});
const prose = (
  text: string,
  highlights: TextbookStep["highlights"] = {},
): TextbookStep => ({
  text,
  highlights,
});

/** Only literal references are inferred. Single-letter angles and continuation
 * lines have explicit full-name highlights alongside the source transcription.
 */
const step = (
  math: string,
  reason?: string,
  highlights?: TextbookStep["highlights"],
): TextbookStep => {
  const angles = [...math.matchAll(/\\angle\s*([A-Z]{3})/g)].map((v) => v[1]);
  const figures = [...math.matchAll(/\\triangle\s*([A-Z]{3})/g)].map(
    (v) => v[1],
  );
  const sides = [...math.matchAll(/\b([A-Z]{2})\b/g)].map((v) => v[1]);
  return {
    math: [math],
    ...(reason ? { reason } : {}),
    highlights: highlights ?? {
      ...(angles.length ? { angles } : {}),
      ...(sides.length ? { sides } : {}),
      ...(figures.length ? { figures } : {}),
    },
    ...(/^(SSS|SAS|ASA|AAS|RHS)$/.test(reason ?? "")
      ? { conclusion: true }
      : {}),
  };
};

